#ifndef KL_INTTYPES_H
#define KL_INTTYPES_H
/* Freestanding 32-bit ARM formatting tokens used by TinyUSB diagnostics.
 * Diagnostics are disabled; no formatted I/O implementation is linked.
 */
#include <stdint.h>
#define PRIu32 "u"
#define PRIx32 "x"
#define PRIX32 "X"
#define PRId32 "d"
#define PRIu16 "u"
#define PRIx16 "x"
#define PRIu8 "u"
#define PRIx8 "x"
#endif
